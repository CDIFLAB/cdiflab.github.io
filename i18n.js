let language = 'en';
try { if (localStorage.getItem('cdiflab-language') === 'zh') language = 'zh'; } catch (_) {}
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
function translate(text) {
  if (language !== 'zh') return text;
  const core = text.trim();
  let translated = ZH[core];
  const portrait = /^Portrait of (.+)$/.exec(core);
  const profile = /^View (.+)’s profile$/.exec(core);
  if (portrait) translated = `${ZH[portrait[1]] || portrait[1]}的照片`;
  if (profile) translated = `查看${ZH[profile[1]] || profile[1]}的个人主页`;
  return translated === undefined ? text : text.replace(core, translated);
}
function localizePage() {
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script, style, .language-switch')) continue;
    if (!originalText.has(node)) originalText.set(node, node.textContent);
    node.textContent = translate(originalText.get(node));
  }
  document.querySelectorAll('[aria-label], img[alt]').forEach(element => {
    if (element.closest('.language-switch')) return;
    if (!originalAttributes.has(element)) originalAttributes.set(element,
      Object.fromEntries(['aria-label','alt'].filter(a=>element.hasAttribute(a)).map(a=>[a,element.getAttribute(a)])));
    for (const [attr, text] of Object.entries(originalAttributes.get(element))) element.setAttribute(attr, translate(text));
  });
  document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === language)));
  document.querySelector('meta[name="description"]').content = language === 'zh'
    ? '西北工业大学跨域智能飞行实验室（CDIFLab）。'
    : 'Cross-Domain Intelligent Flight Lab (CDIFLab), Northwestern Polytechnical University.';
}
